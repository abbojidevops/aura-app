// Database layer: PostgreSQL via node-postgres (pg), with a small adapter.
// - Positional params use `?` (converted to $1, $2, …).
// - Named params use `@name` (object argument), each name maps to one $n.
// - Timestamps come back as UTC strings "YYYY-MM-DD HH:MM:SS" (same shape the API has always returned).
// Set DATABASE_URL, e.g. postgres://aura:secret@localhost:5432/aura
const { Pool, types } = require('pg');

// COUNT(*) and other int8 values come back as JS numbers, not strings.
types.setTypeParser(20, (v) => parseInt(v, 10));
// timestamptz -> "YYYY-MM-DD HH:MM:SS" in UTC.
types.setTypeParser(1184, (v) => new Date(v).toISOString().slice(0, 19).replace('T', ' '));

if (!process.env.DATABASE_URL) {
  console.warn('[db] DATABASE_URL is not set. Falling back to postgres://aura:aura@localhost:5432/aura (development only).');
}
const pool = new Pool({
  connectionString: process.env.DATABASE_URL || 'postgres://aura:aura@localhost:5432/aura',
  max: Number(process.env.PG_POOL_MAX) || 10,
});

function convert(sql, params) {
  if (params === undefined || params === null) return { text: sql, values: [] };
  if (Array.isArray(params)) {
    let i = 0;
    return { text: sql.replace(/\?/g, () => `$${++i}`), values: params };
  }
  const names = [];
  const text = sql.replace(/@([A-Za-z_]\w*)/g, (_, name) => {
    let idx = names.indexOf(name);
    if (idx < 0) {
      if (!(name in params)) throw new Error(`Missing SQL parameter @${name}`);
      names.push(name);
      idx = names.length - 1;
    }
    return `$${idx + 1}`;
  });
  return { text, values: names.map((n) => params[n]) };
}

function makeApi(runQuery) {
  const exec = (sql, params) => {
    const { text, values } = convert(sql, params);
    // No parameters -> simple protocol, so multi-statement SQL (schema) works.
    return runQuery(text, values.length ? values : undefined);
  };
  return {
    // rows
    all: async (sql, params) => (await exec(sql, params)).rows,
    get: async (sql, params) => (await exec(sql, params)).rows[0],
    // write: { changes }. Add RETURNING id in SQL to read new ids from `.get`.
    run: async (sql, params) => {
      const r = await exec(sql, params);
      return { changes: r.rowCount };
    },
  };
}

const db = makeApi((text, values) => pool.query(text, values));

// Transaction: fn receives an object with the same all/get/run methods.
db.tx = async (fn) => {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const t = makeApi((text, values) => client.query(text, values));
    const out = await fn(t);
    await client.query('COMMIT');
    return out;
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
};

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL UNIQUE,
  display_name  TEXT NOT NULL,
  email         TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  bio           TEXT NOT NULL DEFAULT '',
  avatar_hue    INTEGER NOT NULL DEFAULT 260,
  is_private    INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower ON users (lower(email));

CREATE TABLE IF NOT EXISTS sessions (
  token      TEXT PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS posts (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  caption       TEXT NOT NULL DEFAULT '',
  media_type    TEXT NOT NULL CHECK (media_type IN ('image','video')),
  media_url     TEXT,
  thumb_url     TEXT,
  width         INTEGER,
  height        INTEGER,
  duration      DOUBLE PRECISION,
  visibility    TEXT NOT NULL DEFAULT 'public' CHECK (visibility IN ('public','followers','private')),
  status        TEXT NOT NULL DEFAULT 'processing' CHECK (status IN ('processing','published','failed','hidden')),
  like_count    INTEGER NOT NULL DEFAULT 0,
  comment_count INTEGER NOT NULL DEFAULT 0,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_posts_status_created ON posts(status, created_at);
CREATE INDEX IF NOT EXISTS idx_posts_user_created ON posts(user_id, created_at);

CREATE TABLE IF NOT EXISTS post_tags (
  post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  tag     TEXT NOT NULL,
  PRIMARY KEY (post_id, tag)
);
CREATE INDEX IF NOT EXISTS idx_post_tags_tag ON post_tags(tag);

CREATE TABLE IF NOT EXISTS follows (
  follower_id  INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  following_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (follower_id, following_id)
);
CREATE INDEX IF NOT EXISTS idx_follows_following ON follows(following_id);

CREATE TABLE IF NOT EXISTS likes (
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  post_id    INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, post_id)
);
CREATE INDEX IF NOT EXISTS idx_likes_post ON likes(post_id);

CREATE TABLE IF NOT EXISTS saves (
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  post_id    INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, post_id)
);

CREATE TABLE IF NOT EXISTS comments (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id    INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body       TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_comments_post ON comments(post_id, id);

CREATE TABLE IF NOT EXISTS notifications (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_id   INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type       TEXT NOT NULL CHECK (type IN ('like','comment','follow')),
  post_id    INTEGER REFERENCES posts(id) ON DELETE CASCADE,
  is_read    INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, id);

CREATE TABLE IF NOT EXISTS conversations (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS conversation_members (
  conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  last_read_id    INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (conversation_id, user_id)
);

CREATE TABLE IF NOT EXISTS messages (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id INTEGER NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body            TEXT NOT NULL,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_messages_conv ON messages(conversation_id, id);

CREATE TABLE IF NOT EXISTS user_feed_settings (
  user_id        INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  mood           TEXT NOT NULL DEFAULT 'inspire',
  friends        INTEGER NOT NULL DEFAULT 80,
  new_creators   INTEGER NOT NULL DEFAULT 60,
  controversial  INTEGER NOT NULL DEFAULT 10
);

CREATE TABLE IF NOT EXISTS reports (
  reporter_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  post_id     INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  reason      TEXT NOT NULL DEFAULT 'other',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (reporter_id, post_id)
);
`;

// Creates tables once. The advisory lock keeps two starting instances from racing.
db.init = async () => {
  await db.tx(async (t) => {
    await t.run('SELECT pg_advisory_xact_lock(7201)');
    await t.run(SCHEMA);
  });
};

db.close = () => pool.end();

module.exports = db;
